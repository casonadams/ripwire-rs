#!/usr/bin/env python3
"""Generate docs/REFERENCE.md from the binary: every CLI flag and every MCP tool.

The flag list comes from `--help` (all flags) and `-h` (the core flags); the tool list comes from the
MCP server's `tools/list`. Nothing here is hand-written, so a new flag or tool needs no manual doc sync.

Usage: scripts/gen-reference.py [--bin PATH] [--check]
  --check   exit 1 when docs/REFERENCE.md is not what the binary would generate (make docs-check)
"""

import argparse
import json
import pathlib
import re
import subprocess
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "docs" / "REFERENCE.md"
FLAG = re.compile(r"^\s+(?:-\w, )?(--[\w-]+)(?:[ =\[<](.*))?$")


def run(binary, *args, stdin=None):
    return subprocess.run(
        [binary, *args], input=stdin, capture_output=True, text=True, timeout=60
    ).stdout


def parse_help(text):
    """[(flag, value, description)] in the order clap prints them."""
    flags, lines = [], text.splitlines()
    for i, line in enumerate(lines):
        match = FLAG.match(line)
        if not match or i + 1 >= len(lines) or not lines[i + 1].startswith("          "):
            continue
        description = lines[i + 1].strip()
        description = re.sub(r"\s*\[(?:default|alias)[^\]]*\]", "", description)
        flags.append((match.group(1), (match.group(2) or "").strip(), description))
    return flags


def mcp_tools(binary):
    requests = "\n".join(
        json.dumps(r)
        for r in (
            {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
                "protocolVersion": "2024-11-05", "capabilities": {},
                "clientInfo": {"name": "gen-reference", "version": "0"}}},
            {"jsonrpc": "2.0", "id": 2, "method": "tools/list", "params": {}},
        )
    )
    reply = run(binary, "mcp", ".", stdin=requests + "\n").strip().splitlines()[-1]
    return sorted(json.loads(reply)["result"]["tools"], key=lambda t: t["name"])


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def render(binary):
    everything = parse_help(run(binary, "--help"))
    core = {flag for flag, _, _ in parse_help(run(binary, "-h"))}
    out = [
        "# Reference (generated)\n",
        "Generated by `scripts/gen-reference.py` from the binary; do not edit. Run `make docs` after changing a flag or tool.\n",
        f"## Core flags ({len(core)})\n\n`ripwire-rs -h` lists these. They answer the two jobs: find, and check.\n",
        "| Flag | Value | What it does |\n|---|---|---|",
    ]
    for flag, value, desc in everything:
        if flag in core:
            out.append(f"| `{flag}` | `{cell(value)}` | {cell(desc)} |")
    others = [f for f in everything if f[0] not in core]
    out += [
        f"\n## All other flags ({len(others)})\n\n`ripwire-rs --help` lists these as well.\n",
        "| Flag | Value | What it does |\n|---|---|---|",
    ]
    out += [f"| `{f}` | `{cell(v)}` | {cell(d)} |" for f, v, d in others]
    tools = mcp_tools(binary)
    out += [
        f"\n## MCP tools ({len(tools)})\n",
        "| Tool | Required arguments | What it does |\n|---|---|---|",
    ]
    for tool in tools:
        required = ", ".join(f"`{r}`" for r in tool["inputSchema"].get("required", []))
        out.append(f"| `{tool['name']}` | {required} | {cell(tool['description'])} |")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--bin", default="target/release/ripwire-rs")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(args.bin)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("::error::docs/REFERENCE.md is stale; run `make docs`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(OUT.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
